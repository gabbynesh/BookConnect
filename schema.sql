-- Proposed schema for a fresh Supabase project. Review existing tables before applying.
create table public.books (
 id bigint generated by default as identity primary key,
 title text not null, author text not null, genre text not null,
 available boolean not null default true
);
create table public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 display_name text not null
);
create table public.reservations (
 id bigint generated always as identity primary key,
 user_id uuid not null references public.profiles(id) on delete cascade,
 book_id bigint not null references public.books(id),
 created_at timestamptz not null default now(),
 status text not null default 'reserved' check(status in ('reserved','borrowed','returned','cancelled'))
);
create unique index one_active_reservation on public.reservations(book_id) where status in ('reserved','borrowed');
alter table public.books enable row level security;
alter table public.profiles enable row level security;
alter table public.reservations enable row level security;
create policy catalog_read on public.books for select to anon, authenticated using (true);
create policy own_profile on public.profiles for all to authenticated using (id=auth.uid()) with check (id=auth.uid());
create policy own_reservations_read on public.reservations for select to authenticated using (user_id=auth.uid());
create policy reserve_available on public.reservations for insert to authenticated with check (user_id=auth.uid() and status='reserved' and exists(select 1 from public.books b where b.id=book_id and b.available));
create policy cancel_own on public.reservations for update to authenticated using (user_id=auth.uid() and status='reserved') with check (user_id=auth.uid() and status='cancelled');
-- Restrict updates to status only; librarian operations require a separate trusted workflow.
revoke update on public.reservations from authenticated;
grant update(status) on public.reservations to authenticated;
